// Generates scripts/cut-pages.mjs from the live Duda sitemap.
// Run once, while Duda is still live. The output is committed so the redirect
// map stays reproducible after the source site is gone.
import { writeFile } from 'node:fs/promises';
import { BASE, PAGES, CASE_STUDIES, CUT_REDIRECTS } from './inventory.mjs';

const xml = await fetch(`${BASE}/sitemap.xml`).then((r) => r.text());

const keep = new Set([
  ...PAGES.map((p) => p.old),
  ...CASE_STUDIES.map((c) => `/case-studies/${c.slug}`),
]);

// Paths already handled by an explicit CUT_REDIRECTS rule must not also appear
// here. Cloudflare's _redirects takes the FIRST match, so a duplicate line
// sending /services/video-editing to / would beat the /services/* rule that
// sends it to /#services.
const claimed = (path) =>
  CUT_REDIRECTS.some(({ from }) =>
    from.endsWith('/*') ? path.startsWith(from.slice(0, -1)) : path === from
  );

const paths = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)]
  .map((m) => new URL(m[1].trim()).pathname)
  // Two sitemap entries are malformed and carry a leading space, which the URL
  // parser percent-encodes. Decode first so the trim actually removes it.
  .map((p) => '/' + decodeURIComponent(p).replace(/^[/\s]+/, '').trim())
  .filter((p) => p !== '/' && !keep.has(p) && !claimed(p));

const unique = [...new Set(paths)].sort();

await writeFile(
  'scripts/cut-pages.mjs',
  '// Generated by scripts/fetch-cut-pages.mjs — do not edit by hand.\n' +
    '// Legacy URLs that are cut from the rebuild and 301 to the homepage.\n' +
    `export const CUT_PAGES = ${JSON.stringify(unique, null, 2)};\n`
);

console.log(`Wrote ${unique.length} cut pages to scripts/cut-pages.mjs`);
