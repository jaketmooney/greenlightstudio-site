// Generates public/_redirects from the URL inventory.
// Generated rather than hand-written so the rules cannot drift from the
// inventory that drove the migration.
import { writeFile, mkdir } from 'node:fs/promises';
import { CASE_STUDIES, CUT_REDIRECTS } from './inventory.mjs';
import { CUT_PAGES } from './cut-pages.mjs';

// Case studies whose legacy path differs from their new one.
// Written out explicitly, one line per URL, for two reasons:
//   1. Slugs were shortened during migration, so source and destination share
//      no stem - a :slug placeholder would carry the old slug through.
//   2. Cloudflare placeholders match whole path segments only, so a rule like
//      /case-study-:slug is invalid (case-study- is a prefix within a segment).
const moved = CASE_STUDIES.filter((c) => c.old !== `/case-studies/${c.slug}`);

// Two sitemap entries carry a stray leading space. They 404 on the live site
// today; redirecting them costs two lines and fixes a standing defect.
const MALFORMED = [
  { from: '/%20cro-case-study-workwear-branding-sme-growth', to: '/our-work/' },
  { from: '/%20video-marketing-industrial-b2b-2025', to: '/' },
];

const pad = (s, n) => s + ' '.repeat(Math.max(1, n - s.length));
const width = Math.max(
  ...[...moved.map((c) => c.old), ...CUT_REDIRECTS.map((r) => r.from), ...CUT_PAGES].map(
    (s) => s.length
  )
) + 2;

// Cloudflare evaluates rules top-down and takes the first match, and its docs
// state that static rules must come before dynamic (wildcard/placeholder) ones.
// So every exact path is emitted first and the wildcards go last.
const isDynamic = (from) => from.includes('*') || /\/:/.test(from);
const cutStatic = CUT_REDIRECTS.filter((r) => !isDynamic(r.from));
const cutDynamic = CUT_REDIRECTS.filter((r) => isDynamic(r.from));

const lines = [
  '# Generated by scripts/build-redirects.mjs - do not edit by hand.',
  '# Regenerate with: npm run redirects',
  '#',
  '# Cloudflare takes the FIRST matching rule, and requires static rules',
  '# before dynamic ones, so ordering here is deliberate.',
  '',
  `# Case studies: legacy paths to standardised /case-studies/<slug> (${moved.length})`,
  ...moved.map((c) => `${pad(c.old, width)}/case-studies/${c.slug}/  301`),
  '',
  '# Sections cut from the rebuild',
  ...cutStatic.map((r) => `${pad(r.from, width)}${r.to}  301`),
  '',
  '# Malformed legacy URLs (stray leading space, 404 on the old site)',
  ...MALFORMED.map((r) => `${pad(r.from, width)}${r.to}  301`),
  '',
  `# Blog and insight posts, cut from the rebuild (${CUT_PAGES.length})`,
  ...CUT_PAGES.map((p) => `${pad(p, width)}/  301`),
  '',
  '# Dynamic rules last, per Cloudflare ordering requirements',
  ...cutDynamic.map((r) => `${pad(r.from, width)}${r.to}  301`),
  '',
];

await mkdir('public', { recursive: true });
await writeFile('public/_redirects', lines.join('\n'));

const count = lines.filter((l) => l.trim().endsWith('301')).length;
console.log(`Wrote ${count} redirect rules to public/_redirects`);
